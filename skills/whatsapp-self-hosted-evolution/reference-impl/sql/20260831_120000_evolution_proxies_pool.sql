-- T2 of evolution/PROXY_PER_CHANNEL_PLAN.md: the per-channel Evolution proxy POOL.
--
-- Each row is one static (sticky) residential/ISP/mobile proxy IP. Assignment
-- (T3) claims a free row per channel at connect; release (T4) frees it on
-- delete/disconnect. This is what gives each merchant its own egress IP so a
-- WhatsApp ban on one shared IP can't take down multiple merchants at once.
--
-- SERVICE-ROLE ONLY. proxy_url carries credentials (user:pass@host:port) and must
-- NEVER reach a client. RLS is enabled with NO authenticated/anon policies =>
-- default-deny to every client; billing-server reaches it through the service_role
-- key (supabaseAdmin), which bypasses RLS. This is deliberately NOT a
-- role_permissions resource (there is no client path to it at all).

CREATE TABLE IF NOT EXISTS public.evolution_proxies (
  id                   bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  proxy_url            text NOT NULL,               -- full URL incl auth, e.g. http://user:pass@host:port (or socks5://)
  label                text,                        -- human note, e.g. 'IPRoyal US #1'
  status               text NOT NULL DEFAULT 'available'
                         CHECK (status IN ('available','assigned','dead')),
  assigned_channel_id  bigint REFERENCES public.whatsapp_channels(id) ON DELETE SET NULL,
  health               text CHECK (health IS NULL OR health IN ('ok','failing')),
  provider             text,                        -- 'manual' | 'iproyal' | ... (drives the auto-buy release adapter later)
  provider_order_id    text,                        -- provider's order/IP id, so a future adapter can cancel/return it
  last_checked_at      timestamptz,                 -- last health probe (T6)
  assigned_at          timestamptz,
  notes                text,
  created_at           timestamptz NOT NULL DEFAULT now(),
  updated_at           timestamptz NOT NULL DEFAULT now()
);

-- Fast "find a free proxy" scan for the T3 atomic claim.
CREATE INDEX IF NOT EXISTS idx_evolution_proxies_status
  ON public.evolution_proxies (status);

-- A channel holds at most ONE proxy at a time (belt-and-suspenders for the claim).
CREATE UNIQUE INDEX IF NOT EXISTS uniq_evolution_proxies_assigned_channel
  ON public.evolution_proxies (assigned_channel_id)
  WHERE assigned_channel_id IS NOT NULL;

ALTER TABLE public.evolution_proxies ENABLE ROW LEVEL SECURITY;

-- Supabase's default privileges auto-grant new public tables to anon/authenticated;
-- revoke that here so the credentials table is service-role only (RLS with no
-- policies would deny them anyway, but we also remove the grant).
REVOKE ALL ON public.evolution_proxies FROM anon, authenticated;
GRANT ALL ON public.evolution_proxies TO service_role;
